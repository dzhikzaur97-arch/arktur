SHIPS = {}
def ship(id, fac='player', hull=None):
    def deco(fn):
        SHIPS[id] = (fn, fac, hull); return fn
    return deco

def hp_row(n, y0, y1, z=None, x=0.0, s=0.07, M=None, zf=None):
    """Орудийные точки: парами по бортам от носа к корме, нечётная — по оси; каждая садится на обшивку лучом."""
    pts = []
    pairs, single = n // 2, n % 2
    for i in range(pairs):
        y = y0 + (y1 - y0) * (i / max(1, pairs - 1) if pairs > 1 else 0.5)
        for sd in (1, -1): pts.append((sd * x, y))
    if single: pts.insert(0, (0, y0 + (y1 - y0) * (0.5 if pairs else 0)))
    for (px, py) in pts: mount(px, py, s, M)

