def clean():
    bpy.ops.wm.read_factory_settings(use_empty=True)

def build(sid):
    fn, fac, hull = SHIPS[sid]
    clean()
    scene = bpy.context.scene
    K.S['col'] = bpy.data.collections.new(sid); scene.collection.children.link(K.S['col'])
    M = materials(fac, hull)
    fn(M)
    return scene

def studio(scene):
    obs = [o for o in K.S['col'].objects if o.type == 'MESH']
    mn = Vector((1e9,) * 3); mx = Vector((-1e9,) * 3)
    for o in obs:
        for c in o.bound_box:
            w = o.matrix_world @ Vector(c); mn = Vector(map(min, mn, w)); mx = Vector(map(max, mx, w))
    ctr = (mn + mx) / 2; rad = (mx - mn).length / 2
    w = bpy.data.worlds.new('Космос'); scene.world = w; w.use_nodes = True
    w.node_tree.nodes['Background'].inputs['Color'].default_value = (0.012, 0.016, 0.026, 1); w.node_tree.nodes['Background'].inputs['Strength'].default_value = 1.0
    def L(name, loc, e, size, col=(1, 1, 1)):
        l = bpy.data.lights.new(name, 'AREA'); l.energy = e * rad * rad; l.size = size * rad; l.color = col
        o = bpy.data.objects.new(name, l); o.location = ctr + Vector(loc) * rad; scene.collection.objects.link(o)
        o.rotation_euler = (ctr - o.location).to_track_quat('-Z', 'Y').to_euler()
    L('Ключ', (-2.2, 2.0, 2.6), 70, 2.5); L('Заполнение', (2.5, 0.8, 0.6), 14, 3, (0.7, 0.8, 1.0)); L('Контр', (0.6, -3, 1.4), 140, 2, (1.0, 0.85, 0.7))
    cam = bpy.data.cameras.new('Камера'); cam.lens = 55
    c = bpy.data.objects.new('Камера', cam); scene.collection.objects.link(c); scene.camera = c
    d = Vector((-0.78, 0.62, 0.42)).normalized()
    c.location = ctr + d * rad * 3.3
    c.rotation_euler = (ctr - c.location).to_track_quat('-Z', 'Y').to_euler()
    scene.render.engine = 'CYCLES'; scene.cycles.device = 'CPU'; scene.cycles.samples = 40; scene.cycles.use_denoising = True
    scene.render.resolution_x = 1200; scene.render.resolution_y = 760
    scene.view_settings.view_transform = 'AgX'; scene.view_settings.look = 'AgX - Medium High Contrast'

ids = [i for i in SHIPS if not ONLY or i in ONLY]
for sid in ids:
    scene = build(sid)
    bpy.ops.export_scene.gltf(filepath=os.path.join(OUT, sid + '.glb'), export_format='GLB', export_apply=True, export_extras=True,
                              export_lights=False, export_cameras=False, export_yup=True, export_texcoords=False, export_materials='EXPORT')
    # сжатие для игры — отдельно: node tools/compress-ships.mjs (квантование + meshopt)
    studio(scene)
    bpy.ops.wm.save_as_mainfile(filepath=os.path.join(OUT, sid + '.blend'))
    if RENDER:
        scene.render.filepath = os.path.join(OUT, sid + '.png'); bpy.ops.render.render(write_still=True)
    print('корабль готов:', sid, os.path.getsize(os.path.join(OUT, sid + '.glb')) // 1024, 'КБ')
