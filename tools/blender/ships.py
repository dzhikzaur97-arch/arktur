def beam(name, p1, p2, w, material, h=None):
    """Балка фермы между двумя точками."""
    a, b = Vector(p1), Vector(p2); d = b - a
    o = box(name, w, d.length, h or w, tuple((a + b) / 2), material, 0.003)
    o.rotation_euler = d.to_track_quat('Y', 'Z').to_euler()
    return o


def prism(name, pts, depth, material, shrink=1.0, bev=0.003):
    """Грань-плита: многоугольник pts (3D) с толщиной depth (вектор назад); shrink < 1 — зазор-шов вокруг."""
    c = sum((Vector(p) for p in pts), Vector()) / len(pts)
    P = [c + (Vector(p) - c) * shrink for p in pts]
    bm = bmesh.new(); D = Vector(depth)
    a = [bm.verts.new(p) for p in P]; b = [bm.verts.new(p + D) for p in P]
    bm.faces.new(a); bm.faces.new(b[::-1])
    for i in range(len(P)):
        j = (i + 1) % len(P); bm.faces.new((a[i], b[i], b[j], a[j]))
    return K._finish(name, bm, material, bev, 25)

def truss(name, p1, p2, w, M):
    """Решётчатая ферма: четыре пояса и диагональные раскосы — одним объектом."""
    a, b = Vector(p1), Vector(p2); d = b - a; L = d.length; d.normalize()
    up = Vector((0, 0, 1)); side = d.cross(up)
    if side.length < 1e-4: side = d.cross(Vector((1, 0, 0)))
    side.normalize(); u = side.cross(d).normalized()
    bm = bmesh.new(); t = w * 0.12
    for sx in (-0.5, 0.5):
        for sz in (-0.5, 0.5): bm_box(bm, (a + b) / 2 + side * w * sx + u * w * sz, d, L, t, t, u)
    n = max(2, int(L / (w * 1.2)))
    for i in range(n):
        q1 = a + d * (L * i / n); q2 = a + d * (L * (i + 1) / n)
        for (s1, z1, s2, z2) in ((-0.5, 0.5, 0.5, 0.5), (-0.5, -0.5, 0.5, -0.5), (0.5, -0.5, 0.5, 0.5), (-0.5, -0.5, -0.5, 0.5)):
            e1 = q1 + side * w * s1 + u * w * z1; e2 = q2 + side * w * s2 + u * w * z2
            bm_box(bm, (e1 + e2) / 2, e2 - e1, (e2 - e1).length, t * 0.7, t * 0.7, u)
    return bm_obj(name, bm, M['hull2'])


